/**
 * Research pipeline: Researcher -> Analyst -> Writer.
 *
 * Port of the Python `pipeline.py` (OpenAI Agents SDK) to plain fetch calls against
 * the Responses API (the same API the Python version used), which works with both
 * OpenAI and Azure OpenAI / Foundry (v1 endpoint) and runs natively in Workers.
 */

import { ConfigError, type Env } from "./types";

// --------------------------------------------------------------------------- config

interface Settings {
  baseUrl: string;
  apiKey: string;
  models: { researcher: string; analyst: string; writer: string };
}

function settings(env: Env): Settings {
  if (!env.TAVILY_API_KEY) throw new ConfigError("TAVILY_API_KEY is not configured on the server.");

  if (["1", "true", "yes"].includes((env.USE_AZURE ?? "false").trim().toLowerCase())) {
    let endpoint = (env.AZURE_OPENAI_ENDPOINT ?? "").trim().replace(/\/+$/, "");
    const apiKey = env.AZURE_OPENAI_API_KEY;
    if (!endpoint || !apiKey) {
      throw new ConfigError("AZURE_OPENAI_ENDPOINT / AZURE_OPENAI_API_KEY are not configured on the server.");
    }
    for (const suffix of ["/openai/v1", "/openai"]) {
      if (endpoint.endsWith(suffix)) endpoint = endpoint.slice(0, -suffix.length);
    }
    return {
      baseUrl: `${endpoint}/openai/v1`,
      apiKey,
      models: {
        researcher: env.AZURE_RESEARCHER_DEPLOYMENT || "your-researcher-deployment-name",
        analyst: env.AZURE_ANALYST_DEPLOYMENT || "your-analyst-deployment-name",
        writer: env.AZURE_WRITER_DEPLOYMENT || "your-writer-deployment-name",
      },
    };
  }

  if (!env.OPENAI_API_KEY) throw new ConfigError("OPENAI_API_KEY is not configured on the server.");
  return {
    baseUrl: "https://api.openai.com/v1",
    apiKey: env.OPENAI_API_KEY,
    models: {
      researcher: env.RESEARCHER_MODEL || "gpt-6-luna",
      analyst: env.ANALYST_MODEL || "gpt-6-luna",
      writer: env.WRITER_MODEL || "gpt-6-luna",
    },
  };
}

// --------------------------------------------------------------------------- prompts

const RESEARCHER_INSTRUCTIONS = `
## Context
You are a research agent with access to the Tavily search tool.

## Instruction
Given a user query, use the Tavily search tool to find relevant information and summarize the key findings.
Use the search tool at most 3 times.

## Input
- A research query from the user.

## Output
- A summary of key findings in a maximum of 5 bullet points.
`;

const ANALYST_INSTRUCTIONS = `
## Context
You are an analyst who receives research notes generated by the research agent.

## Instruction
Given the research notes, analyze the content and extract key trends, risks, or insights.

## Input
- Research notes (summaries of findings from the research agent).

## Output
- A concise analysis (no more than 2 paragraphs) highlighting key trends, risks, or insights.
`;

const writerInstructions = (french: boolean) => {
  const lang = french ? " entirely in French" : "";
  return `
You are a senior market analyst tasked with generating an executive-level research report${lang}.

## Context
You will receive:
- The original user query (the research question or topic of interest).
- A research summary and an analysis summary produced by other agents.

## Instructions
Synthesize all available information and produce the following outputs${lang}:
1. **Executive Summary:** A concise summary (2-3 sentences) highlighting the most important findings relevant to the original query.
2. **Detailed Markdown Report:** A comprehensive, well-structured report in markdown format (at least 500 words) covering key findings, context, implications, and supporting evidence. Use headings and bullet points.
3. **Follow-up Research Questions:** 3-5 thoughtful follow-up questions for further investigation.

## Output
Return a structured object with:
- \`short_summary\`: The executive summary.
- \`markdown_report\`: The detailed markdown report.
- \`follow_up_questions\`: A list of 3-5 follow-up research questions.
`;
};

// --------------------------------------------------------------------------- schemas

/** Structured-output format for the Responses API (`text.format`). */
const jsonFormat = (name: string, schema: Record<string, unknown>) => ({
  format: { type: "json_schema", name, strict: true, schema },
});

const SUMMARY_TEXT = jsonFormat("AnalysisSummary", {
  type: "object",
  properties: { summary: { type: "string" } },
  required: ["summary"],
  additionalProperties: false,
});

const REPORT_TEXT = jsonFormat("FinalReport", {
  type: "object",
  properties: {
    short_summary: { type: "string" },
    markdown_report: { type: "string" },
    follow_up_questions: { type: "array", items: { type: "string" } },
  },
  required: ["short_summary", "markdown_report", "follow_up_questions"],
  additionalProperties: false,
});

const TAVILY_TOOL = {
  type: "function",
  name: "tavily_search",
  description: "Search the web with Tavily and return a bullet list of title: content.",
  strict: false, // max_results is optional
  parameters: {
    type: "object",
    properties: {
      query: { type: "string" },
      max_results: { type: "integer", description: "Number of results (1-8)" },
    },
    required: ["query"],
  },
};

// --------------------------------------------------------------------------- helpers

interface OutputItem {
  type: string;
  call_id?: string;
  name?: string;
  arguments?: string;
  content?: { type: string; text?: string; refusal?: string }[];
}

interface ModelResponse {
  id: string;
  output: OutputItem[];
}

async function respond(cfg: Settings, body: Record<string, unknown>): Promise<ModelResponse> {
  const res = await fetch(`${cfg.baseUrl}/responses`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${cfg.apiKey}` },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const detail = (await res.text()).slice(0, 500);
    throw new Error(`Model call failed (${res.status}): ${detail}`);
  }
  return (await res.json()) as ModelResponse;
}

function outputText(response: ModelResponse): string {
  for (const item of response.output ?? []) {
    if (item.type !== "message") continue;
    for (const part of item.content ?? []) {
      if (part.type === "refusal") throw new Error("The model declined to answer.");
      if (part.type === "output_text" && part.text) return part.text;
    }
  }
  throw new Error("Model returned no content.");
}

const structured = <T>(response: ModelResponse): T => JSON.parse(outputText(response)) as T;

async function tavilySearch(env: Env, query: string, maxResults: number): Promise<string> {
  const res = await fetch("https://api.tavily.com/search", {
    method: "POST",
    headers: { "Content-Type": "application/json", Authorization: `Bearer ${env.TAVILY_API_KEY}` },
    body: JSON.stringify({
      query,
      // clamp results so a single call can never be expensive
      max_results: Math.min(Math.max(Number.isFinite(maxResults) ? Math.trunc(maxResults) : 3, 1), 8),
    }),
    signal: AbortSignal.timeout(20_000),
  });
  if (!res.ok) return `Tavily API error: ${res.status}`;
  const { results = [] } = (await res.json()) as { results?: { title: string; content: string }[] };
  return results.map((r) => `- ${r.title}: ${r.content}`).join("\n") || "No relevant results found.";
}

// --------------------------------------------------------------------------- steps

const MAX_SEARCHES = 3;

/** Step 1: Researcher searches the web (max 3 searches) and returns up to 5 bullet points. */
export async function runResearch(env: Env, query: string): Promise<string> {
  const cfg = settings(env);
  let searches = 0;
  let previousId: string | undefined;
  let input: unknown = query;

  for (let turn = 0; turn < MAX_SEARCHES + 2; turn++) {
    const response = await respond(cfg, {
      model: cfg.models.researcher,
      instructions: RESEARCHER_INSTRUCTIONS,
      input,
      text: SUMMARY_TEXT,
      // Once the search budget is spent, drop the tool so the model must write its summary.
      ...(searches < MAX_SEARCHES ? { tools: [TAVILY_TOOL] } : {}),
      ...(previousId ? { previous_response_id: previousId } : {}),
    });

    const calls = response.output.filter((item) => item.type === "function_call");
    if (!calls.length) return structured<{ summary: string }>(response).summary;

    const outputs: unknown[] = [];
    for (const call of calls) {
      let output: string;
      if (searches >= MAX_SEARCHES) {
        output = "Search limit reached. Summarize using the results you already have.";
      } else {
        searches++;
        try {
          const args = JSON.parse(call.arguments ?? "{}") as { query: string; max_results?: number };
          output = await tavilySearch(env, args.query, args.max_results ?? 3);
        } catch (err) {
          console.error("tavily_search failed", err);
          output = "Search failed.";
        }
      }
      outputs.push({ type: "function_call_output", call_id: call.call_id, output });
    }
    previousId = response.id;
    input = outputs;
  }
  throw new Error("Researcher did not produce a summary.");
}

/** Step 2: Analyst extracts trends, risks and insights from the research notes. */
export async function runAnalysis(env: Env, researchSummary: string): Promise<string> {
  const cfg = settings(env);
  const response = await respond(cfg, {
    model: cfg.models.analyst,
    instructions: ANALYST_INSTRUCTIONS,
    input: researchSummary,
    text: SUMMARY_TEXT,
  });
  return structured<{ summary: string }>(response).summary;
}

/** Step 3: Writer produces the executive summary, full report and follow-up questions. */
export async function runWriter(
  env: Env,
  query: string,
  researchSummary: string,
  analysisSummary: string,
  french: boolean,
) {
  const cfg = settings(env);
  const response = await respond(cfg, {
    model: cfg.models.writer,
    instructions: writerInstructions(french),
    input: `Original query: ${query}\nResearch summary: ${researchSummary}\nAnalysis summary: ${analysisSummary}`,
    text: REPORT_TEXT,
  });
  return structured<{ short_summary: string; markdown_report: string; follow_up_questions: string[] }>(response);
}
